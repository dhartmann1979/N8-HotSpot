"""
Builds MMDVM-Host.ini and DMRGateway.ini from the settings.

Current MMDVMHost and DMRGateway (g4klx) log via MQTT and connect to a DMR
server only through DMRGateway:

    modem ── MMDVMHost ──(UDP 62032/62031)── DMRGateway ──(HomeBrew)── DMR server
                 │                                │
                 └──────────── MQTT (mosquitto) ──┴──> N8-Hotspot (live data)
"""
from __future__ import annotations

import os
import re
from collections import OrderedDict
from pathlib import Path
from typing import Dict, List, Tuple

from .settings import hotspot_id

Ini = "OrderedDict[str, List[Tuple[str, str]]]"


def _b(v) -> str:
    return "1" if v else "0"


def _sec(ini, name: str, items: List[Tuple[str, object]]) -> None:
    ini[name] = [(k, str(v)) for k, v in items]


def parse_extra(text: str) -> "OrderedDict[str, List[Tuple[str, str]]]":
    out: "OrderedDict[str, List[Tuple[str, str]]]" = OrderedDict()
    sec = None
    for raw in (text or "").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith(";"):
            continue
        m = re.fullmatch(r"\[(.+)\]", line)
        if m:
            sec = m.group(1).strip()
            out.setdefault(sec, [])
            continue
        if sec and "=" in line:
            k, v = line.split("=", 1)
            out[sec].append((k.strip(), v.strip()))
    return out


def merge(ini, extra) -> None:
    """Expert lines replace keys of the same name, or add them / whole sections."""
    for sec, items in extra.items():
        target = ini.setdefault(sec, [])
        for k, v in items:
            for i, (k2, _) in enumerate(target):
                if k2 == k:
                    target[i] = (k, v)
                    break
            else:
                target.append((k, v))


def render(ini, header: str) -> str:
    lines = [f"# {header}", "# Generated by N8-Hotspot. Changes here are overwritten:", "# use the admin area (Settings) instead.", ""]
    for sec, items in ini.items():
        lines.append(f"[{sec}]")
        lines += [f"{k}={v}" for k, v in items]
        lines.append("")
    return "\n".join(lines)


def mmdvm_ini(s: Dict, data_dir: Path) -> str:
    duplex = bool(s["modem.duplex"])
    slot1 = duplex and bool(s["dmr.slot1"])
    ini: "OrderedDict[str, List[Tuple[str, str]]]" = OrderedDict()
    _sec(ini, "General", [("Callsign", s["station.callsign"]), ("Id", hotspot_id(s)), ("Timeout", s["dmr.timeout"]),
                          ("Duplex", _b(duplex)), ("RFModeHang", s["dmr.rf_mode_hang"]),
                          ("NetModeHang", s["dmr.net_mode_hang"]), ("Daemon", 0)])
    _sec(ini, "Log", [("MQTTLevel", 2), ("DisplayLevel", 3)])
    _sec(ini, "MQTT", [("Host", "127.0.0.1"), ("Port", 1883), ("Auth", 0), ("Username", "mmdvm"),
                       ("Password", "mmdvm"), ("Keepalive", 60), ("Name", "mmdvm")])
    _sec(ini, "CW Id", [("Enable", _b(s["dmr.cw_id"])), ("Time", 10), ("Callsign", s["station.callsign"])])
    _sec(ini, "DMR Id Lookup", [("File", data_dir / "DMRIds.dat"), ("Time", 24)])
    _sec(ini, "NXDN Id Lookup", [("File", data_dir / "NXDN.csv"), ("Time", 24)])
    _sec(ini, "Modem", [
        ("Protocol", "uart"), ("UARTPort", s["modem.port"]), ("UARTSpeed", s["modem.speed"]),
        ("RXFrequency", s["modem.rx_freq"]), ("TXFrequency", s["modem.tx_freq"] if duplex else s["modem.rx_freq"]),
        ("TXInvert", _b(s["modem.tx_invert"])), ("RXInvert", _b(s["modem.rx_invert"])),
        ("PTTInvert", _b(s["modem.ptt_invert"])), ("TXDelay", s["modem.tx_delay"]),
        ("RXOffset", s["modem.rx_offset"]), ("TXOffset", s["modem.tx_offset"]), ("DMRDelay", s["modem.dmr_delay"]),
        ("RXLevel", s["modem.rx_level"]), ("TXLevel", s["modem.tx_level"]), ("RXDCOffset", 0), ("TXDCOffset", 0),
        ("RFLevel", s["modem.rf_level"]), ("RSSIMappingFile", data_dir / "RSSI.dat"), ("UseCOSAsLockout", 0),
        ("Trace", 0), ("Debug", 0)])
    _sec(ini, "Transparent Data", [("Enable", 0)])
    _sec(ini, "D-Star", [("Enable", 0)])
    _sec(ini, "DMR", [("Enable", 1), ("Beacons", 0), ("ColorCode", s["dmr.color_code"]),
                      ("SelfOnly", _b(s["dmr.self_only"])), ("EmbeddedLCOnly", 0), ("DumpTAData", 1),
                      ("TalkerAlias", _b(s["dmr.talker_alias"])), ("CallHang", s["dmr.call_hang"]),
                      ("TXHang", s["dmr.tx_hang"])])
    _sec(ini, "DMR Trunking", [("Enable", 0)])
    for m in ("System Fusion", "P25", "NXDN", "POCSAG", "FM"):
        _sec(ini, m, [("Enable", 0)])
    _sec(ini, "D-Star Network", [("Enable", 0)])
    _sec(ini, "DMR Network", [("Enable", _b(s["network.enabled"])), ("LocalAddress", "127.0.0.1"), ("LocalPort", 62032),
                              ("GatewayAddress", "127.0.0.1"), ("GatewayPort", 62031), ("Jitter", s["network.jitter"]),
                              ("Slot1", _b(slot1)), ("Slot2", _b(s["dmr.slot2"])), ("Debug", 0)])
    for m in ("System Fusion Network", "P25 Network", "NXDN Network", "POCSAG Network", "FM Network"):
        _sec(ini, m, [("Enable", 0)])
    _sec(ini, "Lock File", [("Enable", 0)])
    _sec(ini, "Remote Control", [("Enable", 0)])
    merge(ini, parse_extra(s.get("expert.mmdvm", "")))
    return render(ini, "MMDVM-Host.ini")


def gateway_ini(s: Dict, data_dir: Path) -> str:
    duplex = bool(s["modem.duplex"])
    hid = hotspot_id(s)
    ini: "OrderedDict[str, List[Tuple[str, str]]]" = OrderedDict()
    _sec(ini, "General", [("Id", hid), ("Timeout", 10), ("RptAddress", "127.0.0.1"), ("RptPort", 62032),
                          ("LocalAddress", "127.0.0.1"), ("LocalPort", 62031), ("RuleTrace", 0), ("Daemon", 0),
                          ("TrunkingEnabled", 0), ("Debug", 0)])
    _sec(ini, "Log", [("DisplayLevel", 3), ("MQTTLevel", 2)])
    _sec(ini, "Voice", [("Enabled", 0), ("Language", "en_GB"), ("Directory", "/usr/local/share/DMRGateway/Audio")])
    _sec(ini, "Info", [("Callsign", s["station.callsign"]), ("TXFrequency", s["modem.tx_freq"] if duplex else s["modem.rx_freq"]),
                       ("RXFrequency", s["modem.rx_freq"]), ("Power", s["station.power"]),
                       ("ColorCode", s["dmr.color_code"]), ("Duplex", _b(duplex)),
                       ("Slot1", _b(duplex and s["dmr.slot1"])), ("Slot2", _b(s["dmr.slot2"])),
                       ("Latitude", s["station.latitude"]), ("Longitude", s["station.longitude"]),
                       ("Height", s["station.height"]), ("Location", s["station.location"] or "Hotspot"),
                       ("Description", s["station.description"] or "N8 Hotspot"), ("URL", s["station.url"] or "")])
    _sec(ini, "XLX Network", [("Enabled", 0)])
    net = [("Enabled", _b(s["network.enabled"])), ("Name", s["network.name"] or "N8schicht"), ("Id", hid),
           ("Address", s["network.host"]), ("Port", s["network.port"]), ("Password", s["network.password"])]
    if (s.get("network.options") or "").strip():
        net.append(("Options", s["network.options"].strip()))
    net += [("Location", 1), ("Debug", 0), ("PassAllTG", 1), ("PassAllTG", 2), ("PassAllPC", 1), ("PassAllPC", 2)]
    _sec(ini, "DMR Network 1", net)
    _sec(ini, "GPSD", [("Enable", 0)])
    _sec(ini, "APRS", [("Enable", 0)])
    _sec(ini, "MQTT", [("Address", "127.0.0.1"), ("Port", 1883), ("Keepalive", 60), ("Auth", 0),
                       ("Username", "mmdvm"), ("Password", "mmdvm"), ("Name", "dmr-gateway")])
    _sec(ini, "Dynamic TG Control", [("Enable", 0)])
    _sec(ini, "Remote Commands", [("Enable", 0)])
    merge(ini, parse_extra(s.get("expert.gateway", "")))
    return render(ini, "DMRGateway.ini")


def _write(path: Path, text: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.chmod(tmp, 0o640)            # contains the DMR server password
    os.replace(tmp, path)
    return True


def write_all(s: Dict, data_dir: Path) -> Dict[str, bool]:
    data_dir.mkdir(parents=True, exist_ok=True)
    return {"MMDVM-Host.ini": _write(data_dir / "MMDVM-Host.ini", mmdvm_ini(s, data_dir)),
            "DMRGateway.ini": _write(data_dir / "DMRGateway.ini", gateway_ini(s, data_dir))}
